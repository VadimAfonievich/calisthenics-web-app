## Работа плеч

В стойке активно отталкивайтесь от пола.

Плечи должны стремиться вверх, в сторону ушей.

Не позволяйте корпусу проваливаться между плечами.

## Корпус

Напрягите пресс и ягодицы.

Слегка подкрутите таз.

Избегайте чрезмерного прогиба в пояснице.

Это позволяет превратить тело в единый жёсткий рычаг.

## Стойка у стены

Начинайте со стойки лицом к стене.

Поднимайтесь ногами вверх по стене и постепенно приближайте руки.

